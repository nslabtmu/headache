// 兼容「台」/「臺」用字差異，避免下拉選單用字不同導致查無資料
function normalizeCountyName(name) {
    return name ? name.replace(/^台/, '臺') : name;
}

function getTaiwanDistrictCoord(city, district) {
    const normalizedCity = normalizeCountyName(city);
    const coords = taiwanDistrictCoords[normalizedCity]?.[district];
    if (!coords) return null;
    return { lat: coords[0], lon: coords[1] };
}
